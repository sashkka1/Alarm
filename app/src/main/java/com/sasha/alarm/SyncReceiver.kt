package com.sasha.alarm

import android.content.BroadcastReceiver
import android.content.Context
import android.content.Intent
import android.util.Log
import com.sasha.alarm.core.SyncRetry
import com.sasha.alarm.platform.AlarmScheduling
import com.sasha.alarm.platform.EventLog
import com.sasha.alarm.platform.LogSender
import com.sasha.alarm.platform.PhoneSteps
import com.sasha.alarm.platform.PhoneUsage
import com.sasha.alarm.platform.SyncStateStore
import java.util.Calendar
import java.util.concurrent.Executors

/**
 * Ежедневная отдача журнала компьютеру.
 *
 * Будится раз в сутки в обеденное окно — тогда же, когда компьютер поднимает приём.
 * Не достучались (ноутбук выключен, телефон вне дома) — не беда: журнал целиком
 * никуда не девается и уедет следующей попыткой, а компьютер отбросит уже известное.
 *
 * ⚠️ **Служебный таймер, а не будильник.** Ставится через `setExactAndAllowWhileIdle` —
 * `setAlarmClock` предназначен только для боевого будильника (P0 №4), и вешать на него
 * передачу файлов значило бы показывать владельцу системную иконку будильника на обед.
 *
 * ⚠️ Повторов у таймера нет: каждое срабатывание планирует следующее. Так расписание
 * переживает и перезагрузку, и перевод часов — время следующего пуска считается заново
 * от текущего момента.
 */
class SyncReceiver : BroadcastReceiver() {

    override fun onReceive(context: Context, intent: Intent) {
        val app = context.applicationContext
        schedule(app)

        // Возврат продолжает уже начатую цепочку, всё остальное (обед, кнопка, кабель)
        // начинает новую. Отличать обязательно: иначе каждый возврат обнулял бы счётчик
        // и телефон стучался бы каждые два часа до скончания века.
        val isReturn = intent.action == AlarmScheduling.ACTION_SYNC_RETRY

        // 🔴 **Работа уходит в службу, а приёмник кончается здесь** (14.09.2026). Прежде
        // заход шёл прямо тут, на `goAsync()`, и это его и погубило: бродкасту система
        // отводит срок, а заход занимает около сорока секунд — снимок ~23 с плюс отдача
        // журнала целиком ещё ~19 с. 14 сентября таймер сработал в 10:00:29, а в 10:01:00
        // Android снял бродкаст ANR'ом посреди `LogSender.handOver`. Разбор — в [SyncService].
        if (SyncService.start(app, isReturn)) return

        // ⚠️ **Фолбэк, а не основной путь.** Система не пустила службу — заход всё равно
        // идёт прежним способом: успеть он может не всегда, но ноль попыток хуже одной
        // (P0 №7 — тишина как результат ошибки запрещена).
        Log.w(TAG, "служба не поднялась, идём прежним путём — со сроком")
        val pending = goAsync()
        Executors.newSingleThreadExecutor().execute {
            try {
                collectAndSend(app, isReturn)
            } catch (e: Exception) {
                Log.w(TAG, "передача не удалась", e)
            } finally {
                pending.finish()
            }
        }
    }

    companion object {
        private const val TAG = "SyncReceiver"

        /**
         * Запустить передачу с компьютера, не дожидаясь обеда:
         * ```
         * adb shell am broadcast -a com.sasha.alarm.SYNC_NOW -n com.sasha.alarm/.SyncReceiver
         * ```
         * Пара к `TEST_TRIGGER`: то же назначение — проверить работу по кабелю, не трогая
         * телефон руками. Ничего опасного не делает, поэтому и открыт наружу.
         */
        const val ACTION_NOW = "com.sasha.alarm.SYNC_NOW"

        /**
         * Час, в который телефон отдаёт журнал.
         *
         * ⚠️ **Десять утра, а не час дня** (владелец, 2026-09-03). Прежний час дня достался
         * от обеденной задачи на компьютере, которой больше нет: компьютер слушает всё
         * время, пока включён, и держать передачу привязанной к обеду незачем. К десяти
         * ночь уже кончилась и утро с ней, то есть данные приезжают целыми и раньше.
         *
         * 🔴 **Это же число знает компьютер** — `SyncHealth.SYNC_HOUR` в проекте Sashboard,
         * по нему он решает, не пропущена ли сегодняшняя передача. Разойдутся — и он
         * начнёт жаловаться на исправный телефон либо промолчит о настоящем отказе.
         */
        const val HOUR = 10

        /**
         * Окно снимка использования — двое суток, а не одни.
         *
         * Запас на пропущенный день: телефон мог быть вне дома, выключен или без сети.
         * Повторы ничего не стоят — компьютер отбрасывает уже известные строки сам.
         */
        private const val SNAPSHOT_WINDOW_MS = 2 * 24 * 60 * 60 * 1000L

        /** Сколько корзин шагов считается большим снимком, которому нужно долгое ожидание записи. */
        private const val BIG_STEPS_SNAPSHOT = 1_000

        /** Ожидание записи для большого снимка шагов — см. `collectAndSend`. */
        private const val BIG_FLUSH_TIMEOUT_MS = 20_000L

        /**
         * Собрать всё и отдать компьютеру — единственный путь передачи в приложении.
         *
         * 🔴 **Кнопка «Передать статистику» ходит сюда же** (владелец, 2026-08-29:
         * «кнопка должна собирать вообще всё … и всё это передавать»). Прежде она звала
         * только `LogSender.send()`, то есть отправляла лежащее в журнале, а снимок
         * пользования телефоном не снимала вовсе — снимок делала одна ежедневная задача.
         * Наружу это выглядело так, будто телефоном сегодня не пользовались: 29 августа
         * владелец выгрузил данные руками в 8:30 и в 9:28, и оба раза `phone.usage`
         * не прибавился ни на строку, хотя телефон был в работе с утра.
         *
         * 🔴 **Одна неудачная попытка передачей не считается** (владелец, 02.09.2026).
         * Заход — это попытки раз в две секунды в течение пятнадцати; не вышло — возврат
         * через два часа, и так до трёх раз, а дальше ждём следующего дня. Правило и все
         * числа живут в `SyncRetry` в ядре, здесь только его исполнение: когда стучаться —
         * решает ядро, чем кончилось — знает платформа.
         *
         * ⚠️ **Возврат назначается ПЕРЕД заходом, а не по его исходу** (14.09.2026) — см.
         * `SyncRetry.spentAfterArming`. Порядок здесь и есть надёжность: заход может не
         * пережить сам себя, и тогда единственное, что приведёт нас обратно, — путь назад,
         * положенный заранее.
         *
         * ⚠️ Снимок использования снимается **один раз на заход**, а не на каждую попытку:
         * он читает недельную историю системы и стоит куда дороже самой отправки.
         *
         * ⚠️ Зовётся только с фонового потока: внутри и сеть, и работа с файлами. Зовут
         * отсюда двое — [SyncService] по таймеру и кнопка в `MainActivity`; у обоих срока
         * нет, и это единственное, что отличало ручную передачу от суточной до 14.09.2026.
         *
         * @param isReturn это возврат в уже начатой цепочке, а не новый её первый заход
         */
        @JvmStatic
        @JvmOverloads
        fun collectAndSend(context: Context, isReturn: Boolean = false): LogSender.Result {
            val app = context.applicationContext
            val state = SyncStateStore(app)
            val now = System.currentTimeMillis()

            // 🔴 **Страховка ставится ДО захода, а снимается успехом** (14.09.2026).
            // Прежде возврат назначался в конце, по исходу, — и когда 14 сентября заход
            // сняли ANR'ом посреди отдачи, до конца дело не дошло: ни возврата, ни записи
            // о попытке, день пропал молча. Теперь наоборот: сначала кладём себе путь
            // назад, потом идём. Умерли на полпути — возврат остался стоять.
            // Правило и счёт потраченного — в `SyncRetry`, здесь только исполнение.
            val spent = if (isReturn) state.returnsSpent() else 0
            val safety = SyncRetry.nextReturnAt(spent, now)
            val spentNow = SyncRetry.spentAfterArming(spent)
            if (safety != null) {
                AlarmScheduling.scheduleSyncRetry(app, safety, SyncReceiver::class.java)
            }
            // ⚠️ «Попытка пошла» кладётся на диск сразу и с `ok = false`. Это не пессимизм,
            // а правда на этот момент: пока заход не кончился успехом, он не удался. Умрём —
            // плашка скажет о неудаче честно, вместо вчерашнего успеха, как было 14.09.
            state.remember(atMillis = now, ok = false, returnsSpent = spentNow)

            // Сначала переписываем к себе историю использования: система хранит её
            // около недели и стирает молча. Только потом отдаём — чтобы свежий
            // снимок уехал этой же передачей.
            val spans = PhoneUsage.snapshot(app, now - SNAPSHOT_WINDOW_MS, now)
            // Музыка снимается тем же окном и той же историей: у играющего проигрывателя
            // работает служба переднего плана, и система помнит её задним числом.
            val music = PhoneUsage.music(app, now - SNAPSHOT_WINDOW_MS, now)
            // Шаги считает служба Xiaomi; переписываем до flush, чтобы уехали этой же передачей.
            // ⚠️ **Окно — вся история базы, а не двое суток** (владелец, 2026-09-13: «старую
            // историю давай использовать»). Повторов это не даёт — уже записанные корзины
            // отсеиваются, — а телефон, пролежавший без сети неделю, догонит пропуск сам.
            val steps = PhoneSteps.snapshot(app, 0L, now)
            Log.i(TAG, "снимок использования: отрезков $spans, музыки $music, корзин шагов $steps")

            // 🔴 Снимок пишется фоновой очередью, а отправка читает файлы. Без ожидания
            // свежие строки не успевали лечь и уезжали только следующей передачей —
            // на компьютере это выглядело как «телефоном сегодня не пользовались».
            // Разобрано 27.08.2026 по живым данным.
            // ⚠️ Большой снимок шагов ждём дольше (переход на минутные корзины, 2026-09-13):
            // первая выгрузка всей истории — сотня тысяч строк, и за две секунды она не ложится,
            // а уезжает частями за несколько передач; обычная передача пишет единицы корзин
            // и ждёт по-прежнему.
            // ⚠️ ~~Двадцать секунд плюс заход в пятнадцать укладываются в шестьдесят,
            // отпущенных фоновому приёмнику.~~ **Этот расчёт был неверен и стоил передачи
            // 14.09.2026:** к снимку и заходу прибавляется сама отдача журнала (~19 с на
            // 192 771 строку), и в срок приёмника сорок с лишним секунд не влезли. Теперь
            // заход живёт в [SyncService], где срока нет вовсе, и считать здесь нечего.
            val log = EventLog(app)
            if (steps > BIG_STEPS_SNAPSHOT) log.flush(BIG_FLUSH_TIMEOUT_MS) else log.flush()

            val result = burst(app)
            Log.i(TAG, "передача журнала: $result")

            // ⚠️ «Нечего отдавать» — это успех, а не отказ: связь была, просто журнал
            // пуст. Считать это провалом значит зажигать плашку на ровном месте.
            val ok = result is LogSender.Result.Sent || result == LogSender.Result.NothingToSend

            // 🔴 Исход кладётся на диск, и это не отладка, а единственный след передачи.
            // 31.08.2026 телефон двое суток ничего не отдавал, и заметили это случайно:
            // `Log.i` на HyperOS не доходит, событий в журнал передача не пишет, и снаружи
            // «не смог» неотличимо от «не пробовал». Теперь об этом говорит плашка.
            if (ok) {
                // Уехало — путь назад больше не нужен, и цепочка начинается с чистого листа.
                AlarmScheduling.cancelSyncRetry(app, SyncReceiver::class.java)
                state.remember(atMillis = System.currentTimeMillis(), ok = true, returnsSpent = 0)
            } else {
                // ⚠️ Страховка уже стоит с начала захода — трогать её не нужно, нужно лишь
                // отметить время последней попытки. Возвраты кончились — снимаем висящий
                // таймер, потому что ставить его было нечем и стоять ему незачем.
                if (safety == null) AlarmScheduling.cancelSyncRetry(app, SyncReceiver::class.java)
                state.remember(
                    atMillis = System.currentTimeMillis(),
                    ok = false,
                    returnsSpent = spentNow,
                )
            }
            return result
        }

        /**
         * Заход: попытки по расписанию из ядра, до первой удачной.
         *
         * ⚠️ Спим не «паузу между попытками», а **до следующего начала**: попытка сама
         * занимает секунду-другую, и складывать её длительность с паузой значило бы
         * растянуть заход вдвое против обещанных пятнадцати секунд.
         *
         * 🔴 **Заход обрывается по часам, а не по числу попыток.** Поймано на телефоне
         * 02.09.2026: при выключенном Wi-Fi одна попытка занимает 2,5 секунды — дольше
         * двухсекундного шага, — попытки выстраиваются встык, и восемь запланированных
         * растянулись на 20 секунд вместо пятнадцати. Приёмнику бродкаста отпущено
         * шестьдесят, так что беды не случилось, но обещание перестало быть правдой.
         * Теперь новая попытка не начинается после [SyncRetry.BURST_WINDOW_MS]; медленная
         * попытка съедает своё место в расписании, а не сдвигает весь хвост.
         */
        private fun burst(context: Context): LogSender.Result {
            val sender = LogSender(context)
            val startedAt = System.currentTimeMillis()
            var last: LogSender.Result = LogSender.Result.NotFound("попыток не было")
            for (offset in SyncRetry.burstOffsets()) {
                val waitFor = startedAt + offset - System.currentTimeMillis()
                if (waitFor > 0) {
                    try {
                        Thread.sleep(waitFor)
                    } catch (e: InterruptedException) {
                        Thread.currentThread().interrupt()
                        return last
                    }
                } else if (System.currentTimeMillis() - startedAt >= SyncRetry.BURST_WINDOW_MS) {
                    break
                }
                last = sender.send()
                if (last is LogSender.Result.Sent || last == LogSender.Result.NothingToSend) return last
            }
            return last
        }

        /** Поставить следующую передачу — на сегодня, если [HOUR] ещё не наступил, иначе на завтра. */
        fun schedule(context: Context) {
            val next = Calendar.getInstance().apply {
                set(Calendar.HOUR_OF_DAY, HOUR)
                set(Calendar.MINUTE, 0)
                set(Calendar.SECOND, 0)
                set(Calendar.MILLISECOND, 0)
                if (timeInMillis <= System.currentTimeMillis()) add(Calendar.DAY_OF_YEAR, 1)
            }
            AlarmScheduling.scheduleResume(
                context = context.applicationContext,
                triggerAtMillis = next.timeInMillis,
                receiver = SyncReceiver::class.java,
            )
            Log.i(TAG, "следующая передача журнала в ${next.time}")
        }
    }
}
