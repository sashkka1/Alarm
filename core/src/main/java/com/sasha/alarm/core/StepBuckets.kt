package com.sasha.alarm.core

/**
 * Шаги из системного шагомера — по минутным корзинам для журнала.
 *
 * ⚠️ **Шаги телефон не считает сам** (владелец, 2026-09-13). Их круглосуточно считает
 * служба Xiaomi и хранит строками «с — по — сколько»; мы только переписываем их к себе
 * при передаче журнала. Строки системы бывают любой длины и режутся где попало, поэтому
 * в журнал идут не они, а корзины с ровными границами: одна и та же корзина на соседних
 * снимках выглядит одинаково, и её легко узнать как уже записанную.
 *
 * ⚠️ **Правило живёт в ядре, потому что это правило, а не системная возможность.** В
 * `:platform` осталось только чтение провайдера — там строки не из чего собрать в тесте.
 */
object StepBuckets {

    /** Строка системного шагомера: шаги за отрезок, границы — мс эпохи. */
    data class Row(val from: Long, val to: Long, val steps: Long)

    /** Корзина журнала: `from` кратен [BUCKET_MS]. */
    data class Bucket(val from: Long, val to: Long, val steps: Long)

    /**
     * Ширина корзины — одна минута. Выровнена по эпохе — в любом поясе с целоминутным
     * смещением это ровно начало минуты, и компьютеру не нужно ничего знать о поясе телефона.
     *
     * ⚠️ **Минута, а не четверть часа** (владелец, 2026-09-13: «сначала много ходил, потом
     * мало — не должно быть прямой на 15 минутах»). Строки системы идут кусками по ~30 с,
     * так что минута ещё держит форму прогулки, а мельче делить уже нечего.
     *
     * ⚠️ До вечера 2026-09-13 корзины были по 15 минут, и они остались в журнале как есть.
     * Их начала совпадают с началами минутных, поэтому уже записанные корзины узнаются по
     * ширине, а не только по началу (`PhoneSteps.snapshot`).
     */
    const val BUCKET_MS = 60_000L

    /**
     * Сколько корзина отлёживается после своего конца, прежде чем уйти в журнал.
     *
     * ⚠️ Последнюю строку система может ещё дописывать. Закрытая корзина пишется один раз
     * и больше не трогается, поэтому писать её раньше, чем шаги в ней осели, значит навсегда
     * занизить её.
     */
    const val SETTLE_MS = 15 * 60_000L

    /**
     * Разложить строки по корзинам.
     *
     * Шаги строки делятся между корзинами пропорционально перекрытию по времени: копятся
     * дробными, а округляются уже по корзине — иначе строка, разрезанная на много корзин,
     * теряла бы шаги на округлении каждого куска.
     *
     * @param now текущее время, от него отсчитывается [SETTLE_MS]
     * @param known начала корзин, уже записанных в журнал
     * @return корзины с шагами, осевшие и незнакомые, по возрастанию начала
     */
    fun of(rows: List<Row>, now: Long, known: Set<Long>): List<Bucket> {
        val sums = HashMap<Long, Double>()
        for (row in rows) {
            if (row.steps <= 0 || row.to < row.from) continue
            if (row.to == row.from) {
                // Строка без длины делить нечем: все шаги уходят в корзину её начала.
                val start = startOf(row.from)
                sums[start] = (sums[start] ?: 0.0) + row.steps
                continue
            }
            val length = (row.to - row.from).toDouble()
            var start = startOf(row.from)
            while (start < row.to) {
                val overlap = minOf(row.to, start + BUCKET_MS) - maxOf(row.from, start)
                if (overlap > 0) {
                    sums[start] = (sums[start] ?: 0.0) + row.steps * overlap / length
                }
                start += BUCKET_MS
            }
        }
        val settled = now - SETTLE_MS
        return sums
            .map { (start, steps) -> Bucket(start, start + BUCKET_MS, Math.round(steps)) }
            .filter { it.steps > 0 && it.to <= settled && it.from !in known }
            .sortedBy { it.from }
    }

    /**
     * Начала уже записанных корзин — для `known` в [of].
     *
     * 🔴 **Узнаются только корзины текущей ширины.** Старые по 15 минут начинаются там же,
     * где минутные, и, попав сюда, заглушили бы каждую пятнадцатую минуту истории навсегда.
     *
     * @param spans `fromMillis` и `toMillis` записанных событий; неполные пропускаются
     */
    fun known(spans: Iterable<Pair<Long?, Long?>>): Set<Long> =
        spans.mapNotNullTo(HashSet()) { (from, to) ->
            if (from != null && to != null && to - from == BUCKET_MS) from else null
        }

    private fun startOf(at: Long): Long = Math.floorDiv(at, BUCKET_MS) * BUCKET_MS
}
