package com.sasha.alarm.core

/**
 * Договор о передаче журнала с телефона на компьютер.
 *
 * Живёт в ядре, чтобы обе стороны читали одни и те же строки и порты: расхождение здесь
 * не поймает ни один тест, оно проявится молчанием в шесть утра.
 *
 * **Направление: телефон — клиент, компьютер — сервер.** Телефон открывает исходящее
 * соединение и никогда ничего не слушает: устройство, лежащее у кровати, не должно
 * иметь открытых портов (ADR-0006).
 *
 * **Как находят друг друга.** Телефон бросает в сеть широковещательный вопрос по UDP,
 * компьютер отвечает. Обычный mDNS потребовал бы библиотеки на стороне компьютера —
 * а здесь хватает тридцати строк на каждой стороне и никаких зависимостей. Не ответили
 * (в сети запрещён широковещательный трафик) — остаётся адрес, вписанный руками.
 *
 * **Что передаётся — только новое** (владелец, 2026-09-14: «если телефон передаёт параметры,
 * которые передавались вчера или позавчера, туда, естественно, не нужно»).
 *
 * ⚠️ **Раньше журнал уходил целиком каждый раз**, и это был осознанный размен: не нужно
 * хранить отметку о доставленном, нечего рассинхронизировать, а хранилище компьютера
 * восстанавливалось из телефона при первой же передаче. Размен перестал сходиться, когда
 * в журнал легла вся история шагов: 192 771 строка — это около 19 секунд эфира **каждый
 * раз**, и они же добили суточную передачу 14.09 (см. `SyncService` в проекте Alarm).
 *
 * 🔴 **Оба прежних свойства сохранены, и это обязательное условие размена.** Сколько у него
 * есть, компьютер говорит сам, первой же строкой ответа ([HAVE]) — телефон не гадает.
 * Стало меньше, чем в прошлый успешный раз, значит хранилище компьютера похудело, и телефон
 * шлёт **всё** заново. То есть отметка на телефоне — ускорение, а не источник правды;
 * правду по-прежнему знает компьютер.
 *
 * ⚠️ **Отметка считает строки в файлах, а не время событий.** Журнал — помесячные файлы,
 * только дозапись; догруженная задним числом история (шаги за прошлые месяцы) дописывается
 * в **старые** файлы, в конец. Отметка «всё после такого-то времени» такую догрузку молча
 * потеряла бы — а строки в конце файла ловятся ей правильно.
 *
 * Разговор целиком:
 * ```
 * телефон → ALARMLOG 2
 * телефон ← ALARMLOG-HAVE 190123      (сколько телефонных событий уже лежит)
 * телефон → {"v":1,"at":...}          (только то, чего там нет)
 * телефон → {"v":1,"at":...}
 * телефон → (пустая строка — конец пачки)
 * телефон ← OK 42
 * ```
 *
 * ⚠️ **Версия 1 понимается по-прежнему** — без строки [HAVE] и, значит, журналом целиком.
 * Это не вежливость к чужому софту, а страховка порядка обновления: телефон и компьютер
 * обновляются двумя разными действиями, и между ними не должно быть суток без статистики.
 */
object LogWire {

    /** Порт, на котором компьютер принимает журнал. */
    const val TCP_PORT = 45573

    /** Порт, на котором компьютер отзывается на широковещательный вопрос. */
    const val UDP_PORT = 45574

    /**
     * Версия разговора.
     *
     * ⚠️ **2 с 2026-09-14:** компьютер отвечает на приветствие строкой [HAVE], и телефон
     * шлёт только недостающее. Версию 1 компьютер понимает по-прежнему — см. [isHello]
     * и [SPOKEN_VERSIONS].
     */
    const val VERSION = 2

    /** Какие версии разговора компьютер принимает. Старая живёт ради порядка обновления. */
    val SPOKEN_VERSIONS = 1..VERSION

    /** С какой версии компьютер называет свой запас строкой [HAVE]. */
    const val HAVE_FROM_VERSION = 2

    /** Приветствие клиента. */
    const val HELLO = "ALARMLOG $VERSION"

    /**
     * Ответ компьютера на приветствие: сколько телефонных событий у него уже лежит.
     *
     * ⚠️ Считаются только пришедшие с телефона — свои `pc.*` компьютер пишет себе сам, и
     * телефон о них не знает. Иначе число никогда не сошлось бы ни с чем, и «новое» каждый
     * раз означало бы «всё».
     */
    const val HAVE = "ALARMLOG-HAVE"

    /** Вопрос в сеть: «где тут компьютер». */
    const val DISCOVER_QUESTION = "ALARMLOG-WHO"

    /** Ответ компьютера. За ним через пробел идёт порт приёма. */
    const val DISCOVER_ANSWER = "ALARMLOG-HERE"

    /** Ответ сервера в конце разговора. За ним через пробел — сколько строк принято. */
    const val ACCEPTED = "OK"

    /**
     * Конец пачки — пустая строка.
     *
     * Годится потому, что строка журнала это всегда объект JSON и пустой быть не может.
     * Отдельного маркера с текстом не нужно, а длину пачки заранее знать необязательно.
     */
    const val END_OF_BATCH = ""

    /** Ответ сервера в текст. */
    fun accepted(count: Int): String = "$ACCEPTED $count"

    /** Сколько строк принял сервер. `null` — ответ непонятен. */
    fun parseAccepted(line: String?): Int? {
        val parts = line?.trim()?.split(' ') ?: return null
        if (parts.firstOrNull() != ACCEPTED) return null
        return parts.getOrNull(1)?.toIntOrNull()
    }

    fun discoverAnswer(port: Int): String = "$DISCOVER_ANSWER $port"

    /** Порт из ответа компьютера. `null` — ответ не наш. */
    fun parseDiscoverAnswer(line: String?): Int? {
        val parts = line?.trim()?.split(' ') ?: return null
        if (parts.firstOrNull() != DISCOVER_ANSWER) return null
        return parts.getOrNull(1)?.toIntOrNull()?.takeIf { it in 1..65535 }
    }

    /**
     * Вопрос телефона: «не пора ли освободиться».
     *
     * ⚠️ Спрашивает **телефон**, а не приказывает компьютер. Так направление остаётся
     * прежним — телефон клиент, портов не открывает (ADR-0006), — и освобождение по
     * сети не требует ни единого послабления в правилах.
     */
    const val ASK_RELEASE = "ALARMLOG-RELEASE?"

    /** Ответ компьютера, когда владелец нажал «Освободить». */
    const val RELEASE_NOW = "ALARMLOG-RELEASE!"

    /** Ответ компьютера, когда освобождать не просили. */
    const val RELEASE_NO = "ALARMLOG-HOLD"

    /** Наш ли это клиент и понимаем ли мы его версию. */
    fun isHello(line: String?): Boolean = helloVersion(line) != null

    /**
     * Версия из приветствия. `null` — не наш клиент либо версия нам незнакома.
     *
     * ⚠️ Нужна отдельно от [isHello] потому, что от версии зависит сам порядок разговора:
     * со второй компьютер вставляет строку [HAVE], с первой — молчит и ждёт пачку.
     */
    fun helloVersion(line: String?): Int? {
        val parts = line?.trim()?.split(' ') ?: return null
        if (parts.firstOrNull() != "ALARMLOG") return null
        return parts.getOrNull(1)?.toIntOrNull()?.takeIf { it in SPOKEN_VERSIONS }
    }

    /** Строка ответа: столько телефонных событий у компьютера уже есть. */
    fun have(count: Int): String = "$HAVE $count"

    /** Сколько у компьютера есть. `null` — строка не про это (старый компьютер молчит). */
    fun parseHave(line: String?): Int? {
        val parts = line?.trim()?.split(' ') ?: return null
        if (parts.firstOrNull() != HAVE) return null
        return parts.getOrNull(1)?.toIntOrNull()?.takeIf { it >= 0 }
    }
}
