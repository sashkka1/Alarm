package com.sasha.alarm.core

/**
 * Единственный источник текущего времени в приложении.
 *
 * Прод — системные часы, тесты — фейк. Прямые вызовы [System.currentTimeMillis]
 * в прикладном коде запрещены уставом (P0 №9): иначе поведение будильника
 * невозможно проверить тестом.
 */
fun interface Clock {
    fun nowMillis(): Long
}
