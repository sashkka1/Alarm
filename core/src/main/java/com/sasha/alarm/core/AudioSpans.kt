package com.sasha.alarm.core

/**
 * Когда играла музыка — отрезками, из запусков и остановок службы проигрывателя.
 *
 * Зачем: владелец слушает музыку во время вечерней растяжки и не считает это
 * пользованием телефоном (2026-09-02: «иногда могу почитать во время растяжки, и я бы не
 * хотел включать это в пользование телефоном»). Разбор статистики на компьютере вычитает
 * эти отрезки из пользования.
 *
 * ⚠️ **Источник — история `UsageStats`, а не звук.** У играющего проигрывателя работает
 * служба переднего плана, и система помнит её запуск и остановку **задним числом**.
 * Поэтому слежения в фоне не нужно вовсе: отрезки снимаются тем же запросом, что и
 * пользование, и не стоят ни батареи, ни живого процесса.
 *
 * ⚠️ **Цена источника: это «проигрыватель работал», а не «звук шёл».** Поставленная на
 * паузу музыка службу может не отпустить. Для вечерней растяжки разницы нет, а точнее
 * системa задним числом не расскажет.
 */
object AudioSpans {

    enum class Mark { STARTED, STOPPED }

    data class Event(val at: Long, val mark: Mark)

    data class Span(val from: Long, val to: Long) {
        val durationMs: Long get() = (to - from).coerceAtLeast(0L)
    }

    /**
     * Собрать отрезки.
     *
     * 🔴 **Незакрытый отрезок не отдаётся вовсе.** Окно снимка кончается «сейчас», и
     * играющая в этот момент музыка получила бы конец по краю окна — а на следующем снимке
     * тот же отрезок пришёл бы с другим концом. В журнале осталось бы два отрезка вместо
     * одного, и оба неверные. Дождаться остановки дешевле: снимок делается не раз в минуту.
     *
     * ⚠️ Два «начали» подряд — это перезапуск службы, начало остаётся первым. Так же
     * устроен разбор записи ночи: система вправе не прислать парную остановку.
     */
    fun of(events: List<Event>): List<Span> {
        val out = mutableListOf<Span>()
        var openedAt: Long? = null
        for (event in events.sortedBy { it.at }) {
            when (event.mark) {
                Mark.STARTED -> if (openedAt == null) openedAt = event.at
                Mark.STOPPED -> {
                    openedAt?.let { start -> if (event.at > start) out.add(Span(start, event.at)) }
                    openedAt = null
                }
            }
        }
        return out
    }
}
