package com.sasha.alarm.core

/**
 * Что делать, когда журнал не уехал.
 *
 * ⚠️ **Правило появилось из живого отказа** (02.09.2026). Владелец нажал «Передать
 * статистику» в 07:40:52, а окно приёма на компьютере поднялось только в 08:23:50 —
 * то есть слушать было некому, и телефон сдался с первой же попытки. Разбор показал,
 * что так же устроена и обеденная передача: поиск компьютера длится 2,5 секунды и не
 * повторяется, а `Sashboard.exe` тратит на собственный запуск 1,7–2,2 секунды. Кто
 * успел, тот и передал.
 *
 * Владелец: «если первое время отправки не сработало — каждые пару секунд попробуй,
 * там секунд пятнадцать. И вернись через два часа. Если через два часа ещё не
 * получится — есть ещё через два, и так, допустим, три раза, и всё. И в случае чего
 * следующий день.»
 *
 * Отсюда две ступени, и они решают разные беды:
 *
 * | Ступень | От чего спасает |
 * |---|---|
 * | **Заход** — попытки раз в [BURST_STEP_MS], пока не вышло [BURST_WINDOW_MS] | компьютер уже просыпается, но ещё не занял порт: гонка на старте |
 * | **Возврат** — новый заход через [RETURN_AFTER_MS], и так [MAX_RETURNS] раза | компьютера в этот момент не было вовсе: выключен, спит, ты в другой сети |
 *
 * ⚠️ **Дальше третьего возврата не ходим намеренно.** Шесть часов стука — это уже не
 * «компьютер занят», а «его сегодня не будет», и долбиться в пустоту до ночи незачем:
 * журнал никуда не денется и уедет завтрашней обеденной передачей целиком.
 *
 * ⚠️ Правило считает **только время**, а не сеть и не сокеты: чем кончилась попытка,
 * знает платформа, а решение «когда следующая» — правило, и ему место здесь.
 */
object SyncRetry {

    /** Через сколько после неудачной попытки пробовать снова внутри одного захода. */
    const val BURST_STEP_MS = 2_000L

    /**
     * Сколько заход длится целиком.
     *
     * Пятнадцать секунд выбраны не на глаз: столько нужно `Sashboard.exe`, чтобы
     * подняться из холодного старта с запасом. Меньше — и гонка остаётся, больше —
     * приёмник бродкаста упирается в отпущенные ему системой шестьдесят секунд.
     */
    const val BURST_WINDOW_MS = 15_000L

    /** Через сколько возвращаться, если весь заход не удался. */
    const val RETURN_AFTER_MS = 2L * 60 * 60 * 1000

    /** Сколько таких возвратов бывает, прежде чем ждать следующего дня. */
    const val MAX_RETURNS = 3

    /**
     * Когда начинать попытки внутри одного захода, отсчёт от его начала.
     *
     * ⚠️ Это **начала** попыток, а не паузы между ними. Попытка сама по себе занимает
     * секунду-другую (поиск компьютера ждёт ответа), и складывать её длительность с
     * паузой значило бы растянуть заход вдвое против обещанных пятнадцати секунд.
     *
     * ⚠️ **Расписание, а не обещание восьми попыток.** Когда попытка длится дольше шага
     * (2,5 секунды поиска против двух секунд шага — обычное дело при недоступной сети),
     * она съедает своё место, и в те же пятнадцать секунд их уложится шесть. Так и надо:
     * держим срок захода, а не число ударов в закрытую дверь.
     */
    fun burstOffsets(): List<Long> = generateSequence(0L) { it + BURST_STEP_MS }
        .takeWhile { it < BURST_WINDOW_MS }
        .toList()

    /**
     * Когда возвращаться после неудачного захода.
     *
     * @param returnsSpent сколько возвратов уже потрачено в этой цепочке
     * @return время следующего возврата; `null` — хватит, ждём следующего дня
     */
    fun nextReturnAt(returnsSpent: Int, nowMillis: Long): Long? =
        if (returnsSpent >= MAX_RETURNS) null else nowMillis + RETURN_AFTER_MS

    /**
     * Кончилась ли цепочка.
     *
     * Отдельным вопросом, потому что о нём спрашивают, не собираясь ничего ставить:
     * плашке важно отличить «ещё вернёмся» от «сегодня уже не приедет».
     */
    fun exhausted(returnsSpent: Int): Boolean = returnsSpent >= MAX_RETURNS

    /**
     * Сколько возвратов потрачено после того, как страховка на следующий заход **уже стоит**.
     *
     * 🔴 **Появилось из живого отказа 14.09.2026, и порядок в нём — главное.** Прежде возврат
     * назначался в КОНЦЕ захода, по его исходу. 14 сентября суточная передача в 10:00:29
     * запустилась, а в 10:01:00 Android снял её ANR'ом посреди отдачи журнала
     * (`LogSender.handOver`, отчёт в `dumpsys dropbox`). До конца захода дело не дошло —
     * значит не дошло и до назначения возврата: день пропал молча, а `sync-state.json`
     * показывал утренний успех, потому что и запись состояния стояла в конце.
     *
     * Теперь порядок обратный, и это **страховка от собственной смерти**: возврат ставится
     * ДО попытки, а снимается только успехом. Умерли на полпути — назначенный возврат
     * остался стоять и приведёт нас обратно через [RETURN_AFTER_MS]. Тот же приём, что у
     * сторожа тревоги (P0 №5): дедлайн кладётся на диск раньше, чем начинается то, что он
     * страхует.
     *
     * ⚠️ **Поэтому счётчик тоже растёт заранее.** Возврат уже занял своё место в цепочке —
     * значит он потрачен, даже если заход после этого не пережил и секунды. Иначе смерть
     * в каждом заходе обнуляла бы счёт, и телефон стучался бы каждые два часа вечно.
     *
     * ⚠️ Цепочка кончилась — прибавлять нечего: страховки не было, тратить нечего.
     */
    fun spentAfterArming(returnsSpent: Int): Int =
        if (exhausted(returnsSpent)) returnsSpent else returnsSpent + 1
}
