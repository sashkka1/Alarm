package com.sasha.alarm.core

/**
 * Громкость в обмен на работу.
 *
 * Правило простое: пока человек действительно отжимается — тихо и не растёт;
 * перестал — громкость возвращается, но **плавно**, а не рывком.
 *
 * Смысл в том, что тишина здесь не подарок, а плата за движение: её нельзя взять
 * один раз и оставить себе. Отсюда и обе величины — короткая память [WORK_MEMORY_MS]
 * (перестал двигаться — через несколько секунд начинает возвращаться) и небыстрый
 * возврат [RETURN_MS] (успеешь продолжить — снова стихнет).
 *
 * ⚠️ Приглушение **мгновенное**, а возврат плавный, и это несимметрично намеренно:
 * награда должна быть сразу и заметной, иначе связи «двигаюсь → тише» не возникает.
 */
object EffortVolume {

    /** Во сколько раз тише, пока идёт работа. Десятая часть — решение владельца 2026-08-16. */
    const val QUIET_FACTOR = 0.1f

    /**
     * Сколько «работает» держится после последнего движения вниз.
     *
     * Больше, чем занимает одно отжимание, — иначе громкость мигала бы между
     * повторами. И заметно меньше, чем пауза отдыхающего.
     */
    const val WORK_MEMORY_MS = 4_000L

    /** За сколько громкость возвращается к полной, если работа прекратилась. */
    const val RETURN_MS = 8_000L

    /**
     * Множитель громкости: [QUIET_FACTOR]..1.
     *
     * @param lastMovementAtMillis когда человек в последний раз пошёл вниз. 0 — ещё ни разу.
     */
    fun factor(lastMovementAtMillis: Long, nowMillis: Long): Float {
        if (lastMovementAtMillis <= 0L) return 1f

        val since = nowMillis - lastMovementAtMillis
        // Часы перевели назад — приглушать не за что. Лишний раз сыграть громко
        // безопаснее, чем тихо: тишина вместо будильника хуже любого другого исхода.
        if (since < 0L) return 1f

        if (since <= WORK_MEMORY_MS) return QUIET_FACTOR

        val returned = ((since - WORK_MEMORY_MS).toFloat() / RETURN_MS).coerceIn(0f, 1f)
        return QUIET_FACTOR + (1f - QUIET_FACTOR) * returned
    }

    /**
     * Идёт ли сейчас нарастание громкости.
     *
     * Пока человек работает — нет: иначе за подход набежало бы столько, что после
     * паузы звук вернулся бы не туда, откуда стих, а заметно выше. Обещание
     * «работаешь — не прибавляется» должно быть верным и после того, как встал.
     */
    fun rampRuns(lastMovementAtMillis: Long, nowMillis: Long): Boolean =
        factor(lastMovementAtMillis, nowMillis) > QUIET_FACTOR

    /** Приглушённые проценты для показа и для проигрывателя. */
    fun percent(basePercent: Int, factor: Float): Int =
        (basePercent.coerceIn(0, 100) * factor).toInt().coerceIn(0, 100)
}
