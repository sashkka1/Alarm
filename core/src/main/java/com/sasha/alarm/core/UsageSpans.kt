package com.sasha.alarm.core

/**
 * Когда телефоном **пользовались**.
 *
 * ⚠️ **Считается по замку, а не по тому, какое приложение было на переднем плане**
 * (владелец, 2026-08-29: «нам бы хотя бы понимать период использования»). Прежнее правило
 * строило отрезки из `ACTIVITY_RESUMED` → `ACTIVITY_PAUSED`, и разобранные 29 августа
 * живые данные показали, чем это плохо:
 *
 * - **сплошной сеанс рассыпался на куски.** Экран горел одним куском 33 минуты, а отрезков
 *   из этого вышло 1,1 + 1,1 + 21,5 = 23,7 минуты: между приложениями оставались дыры,
 *   которых в жизни не было;
 * - **отрезок закрывался чужим событием.** Android при переключении шлёт «A ушло → B
 *   пришло → A остановилось», и отрезок, открытый на B, закрывался остановкой A. Отсюда
 *   же путаница с именами приложений — она владельца не волнует, но время врало вместе с ней;
 * - **секундные вспышки экрана от уведомлений** попадали в пользование наравне с сеансами.
 *
 * Замок отвечает ровно на нужный вопрос: телефон разблокирован — значит человек в нём.
 *
 * ⚠️ **Правило живёт в ядре, потому что это правило, а не системная возможность.** В
 * `:platform` осталось только чтение системных событий — там их не из чего собрать в тесте.
 */
object UsageSpans {

    /** Что случилось с телефоном. Порядок и смысл — единственное, что нужно правилу. */
    enum class Mark {
        /** Замок снят: с этого момента человек в телефоне. */
        UNLOCKED,

        /** Замок вернулся. */
        LOCKED,

        /**
         * Экран погас.
         *
         * ⚠️ Закрывает отрезок наравне с замком, и это не лишняя ветка: при умной
         * разблокировке или без защищённого замка `LOCKED` может не прийти вовсе, а
         * погасший экран значит конец сеанса при любых настройках. Без этого один
         * незакрытый отрезок съедал бы остаток суток.
         */
        SCREEN_OFF,
    }

    data class Event(val at: Long, val mark: Mark)

    data class Span(val from: Long, val to: Long)

    /** Разрыв короче этого не разрывает сеанс: заперся и тут же снял замок обратно. */
    const val GLUE_MS = 60_000L

    /** Короче этого — не пользование: глянул время, ответил на уведомление. */
    const val MIN_SPAN_MS = 30_000L

    /**
     * Отрезки пользования из событий замка и экрана.
     *
     * ⚠️ **Незакрытый отрезок не возвращается.** Телефон в руках прямо сейчас — сеанс ещё
     * не кончился, и записать его пришлось бы концом «сейчас»; следующий снимок увидел бы
     * тот же сеанс целиком и другой парой, то есть в статистику легли бы два наложенных
     * отрезка вместо одного. Терять нечего: окно снимка шире суток.
     *
     * @param events в любом порядке — сортируются здесь.
     */
    fun of(events: List<Event>): List<Span> {
        val sorted = events.sortedBy { it.at }
        val raw = mutableListOf<Span>()
        var openedAt: Long? = null
        for (event in sorted) {
            if (event.mark == Mark.UNLOCKED) {
                if (openedAt == null) openedAt = event.at
            } else {
                val start = openedAt ?: continue
                if (event.at > start) raw.add(Span(start, event.at))
                openedAt = null
            }
        }
        return glue(raw).filter { it.to - it.from >= MIN_SPAN_MS }
    }

    /**
     * Слить соседние отрезки.
     *
     * Без этого «заперся на секунду и снова открыл» превращало один сеанс в два, а при
     * пороге [MIN_SPAN_MS] мелкие половинки ещё и пропадали бы вовсе.
     */
    private fun glue(spans: List<Span>): List<Span> {
        if (spans.isEmpty()) return spans
        val out = mutableListOf(spans.first())
        for (span in spans.drop(1)) {
            val last = out.last()
            if (span.from - last.to <= GLUE_MS) {
                out[out.lastIndex] = Span(last.from, maxOf(last.to, span.to))
            } else {
                out.add(span)
            }
        }
        return out
    }
}
