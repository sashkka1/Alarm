package com.sasha.alarm.core

/**
 * Дошёл ли журнал до компьютера — и надо ли об этом сказать.
 *
 * ⚠️ **Правило появилось из живого отказа** (31.08.2026). Телефон двое суток не передавал
 * данные, и заметили это случайно: о передаче не оставалось **ни следа** — ни события в
 * журнале, ни отметки на экране. `SyncReceiver` писал только `Log.i`, а HyperOS логи
 * приложения глушит. Владелец: «если передача не удалась — просто плашка, что сегодня
 * передача не удалась, и всё».
 *
 * ⚠️ **Молчание считается отказом наравне с ошибкой, и это главное здесь.** Тот отказ был
 * не «попытка провалилась», а «попытки не было вовсе»: сработал таймер или нет — снаружи
 * неотличимо. Правило, смотрящее только на исход последней попытки, промолчало бы ровно
 * в том случае, ради которого его пишут. Поэтому тревога поднимается и по давности успеха.
 */
object SyncHealth {

    /**
     * @param lastAttemptAt когда последний раз пробовали; `null` — не пробовали ни разу
     * @param lastOkAt когда последний раз получилось; `null` — не получалось ни разу
     * @param lastAttemptOk чем кончилась последняя попытка
     */
    data class State(
        val lastAttemptAt: Long?,
        val lastOkAt: Long?,
        val lastAttemptOk: Boolean,
    ) {
        companion object {
            val UNKNOWN = State(lastAttemptAt = null, lastOkAt = null, lastAttemptOk = true)
        }
    }

    enum class Verdict {
        /** Всё дошло, говорить не о чем. */
        FINE,

        /** Пробовали и не вышло. */
        FAILED,

        /** Давно ничего не уезжало — попытки могло и не быть вовсе. */
        STALE,
    }

    /**
     * Сколько журнал может не уезжать, прежде чем это станет тревогой.
     *
     * Передача идёт раз в сутки, поэтому сутки ровно — слишком строго: попытка сдвигается
     * на минуты, и плашка загоралась бы от одного лишь дрожания расписания. Двадцать шесть
     * часов — сутки плюс запас, при котором пропуск **одного** обеда уже виден.
     */
    const val STALE_AFTER_MS = 26L * 60 * 60 * 1000

    /**
     * ⚠️ **Пока не уезжало ни разу, тревоги нет.** Свежая установка ничего ещё не
     * передавала, и встречать владельца жалобой на несуществующий отказ незачем: до первого
     * успеха жаловаться не на что.
     */
    fun verdict(state: State, nowMillis: Long): Verdict {
        if (!state.lastAttemptOk && state.lastAttemptAt != null) return Verdict.FAILED
        val okAt = state.lastOkAt ?: return Verdict.FINE
        return if (nowMillis - okAt >= STALE_AFTER_MS) Verdict.STALE else Verdict.FINE
    }

    /** Сколько часов назад журнал уезжал в последний раз. `null` — не уезжал ни разу. */
    fun hoursSinceOk(state: State, nowMillis: Long): Long? {
        val okAt = state.lastOkAt ?: return null
        return ((nowMillis - okAt).coerceAtLeast(0L)) / (60 * 60 * 1000)
    }
}
