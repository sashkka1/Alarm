package com.sasha.alarm.core

import kotlin.math.PI
import kotlin.math.hypot
import kotlin.math.sin

/**
 * Круг-поводырь: тишина в обмен на палец. Испытание метками, и только оно.
 *
 * Пока палец лежит **внутри** круга, звонка нет вовсе и нарастание стоит. Оторвал
 * или отстал — звук возвращается за [RETURN_MS], и возвращается **к началу
 * нарастания**, а не к набежавшему уровню ([rampHoldAfterRelease]).
 *
 * ⚠️ Круг **всё время едет**, и в этом весь смысл (владелец, 2026-08-25): просто
 * положить палец и забыть нельзя, за тишину приходится непрерывно водить рукой по
 * экрану. Оттого здесь и разрешено то, чего не разрешено кружку с тапами, —
 * полная тишина и замороженное нарастание: работа идёт всё время, пока идёт тишина.
 *
 * ⚠️ Прежний прыгающий кружок с тапами на метках **не показывался вовсе**, то есть
 * сбить громкость в этом испытании было нечем: человек ходит по квартире с
 * телефоном в руке, а попадать по мечущейся точке на ходу — не то занятие.
 *
 * Путь — две синусоиды с некратными периодами (фигура Лиссажу): он не повторяется
 * сколько-нибудь скоро и заполняет всю область, поэтому палец на одном месте не
 * поможет ни через минуту, ни через десять.
 */
object GuideCircle {

    /**
     * Радиус круга. Число в dp: рисует и меряет его `:ui`, но решает, попал ли
     * палец, — ядро ([holds]).
     *
     * Строго по краю (владелец, 2026-08-25): запаса на «отстал, но почти держал»
     * нет, вышел за границу — тишина кончилась.
     */
    const val RADIUS_DP = 36f

    /** Насколько далеко от середины уходит центр — в долях области. */
    const val AMPLITUDE = 0.40f

    /**
     * Периоды хода по осям.
     *
     * Разные и некратные намеренно: при кратных путь вырождается в отрезок или в
     * один и тот же овал, который заучивается рукой за пару кругов.
     */
    const val PERIOD_X_MS = 8_300L
    const val PERIOD_Y_MS = 11_700L

    /** За сколько громкость возвращается к полной после срыва (владелец, 2026-08-25). */
    const val RETURN_MS = 1_500L

    /** Сдвиг вертикали, чтобы в начале круг не стоял ровно посередине. */
    private const val PHASE_Y = 1.05

    /** Где сейчас центр круга — доли ширины и высоты области, 0.1…0.9. */
    fun x(elapsedMs: Long): Float = 0.5f + AMPLITUDE * wave(elapsedMs, PERIOD_X_MS, 0.0)

    fun y(elapsedMs: Long): Float = 0.5f + AMPLITUDE * wave(elapsedMs, PERIOD_Y_MS, PHASE_Y)

    private fun wave(elapsedMs: Long, periodMs: Long, phase: Double): Float =
        sin(2.0 * PI * elapsedMs / periodMs + phase).toFloat()

    /**
     * Держит ли палец круг.
     *
     * @param dxPx смещение пальца от центра круга по горизонтали
     * @param dyPx то же по вертикали
     * @param radiusPx радиус круга на экране
     */
    fun holds(dxPx: Float, dyPx: Float, radiusPx: Float): Boolean =
        hypot(dxPx, dyPx) <= radiusPx

    /**
     * Множитель громкости: 0 — тишина, 1 — как было.
     *
     * @param holding держит ли палец круг прямо сейчас
     * @param releasedAtMillis когда сорвался в последний раз. 0 — ещё ни разу не держал
     */
    fun factor(holding: Boolean, releasedAtMillis: Long, nowMillis: Long): Float {
        if (holding) return 0f
        if (releasedAtMillis <= 0L) return 1f

        val since = nowMillis - releasedAtMillis
        // Часы перевели назад — приглушать не за что. Лишний раз сыграть громко
        // безопаснее, чем тихо: тишина вместо будильника хуже любого другого исхода.
        if (since < 0L) return 1f

        return (since.toFloat() / RETURN_MS).coerceIn(0f, 1f)
    }

    /**
     * Идёт ли сейчас нарастание громкости.
     *
     * Пока палец ведёт круг — нет: иначе за проход по квартире набежало бы столько,
     * что после срыва звонок оказался бы громче, чем был до тишины, и обещание
     * «ведёшь — не прибавляется» стало бы враньём. Отпустил — нарастание идёт
     * снова, не дожидаясь конца возврата.
     */
    fun rampRuns(holding: Boolean): Boolean = !holding

    /**
     * Сколько времени нарастание обязано считать простоем после срыва.
     *
     * После срыва звонок идёт **с начала нарастания**, а не с того уровня, на котором
     * его застали (владелец, 2026-08-27): вернуть человека к громкости, набежавшей за
     * прошлые минуты, значит обесценить проход по квартире с пальцем на круге.
     * Обнуляется именно нарастание — начальная громкость из настроек остаётся, звонок
     * снова начинает свой путь с неё.
     *
     * ⚠️ Это не то же самое, что [factor]: тот за [RETURN_MS] снимает тишину, а здесь
     * решается, к какому уровню он её снимает.
     *
     * ⚠️ У отжиманий правило другое — там звук возвращается туда, откуда стих
     * (владелец, 2026-08-27), см. [EffortVolume].
     *
     * @param startedAtMillis когда началась тревога
     * @param releasedAtMillis когда палец сорвался
     */
    fun rampHoldAfterRelease(startedAtMillis: Long, releasedAtMillis: Long): Long =
        (releasedAtMillis - startedAtMillis).coerceAtLeast(0L)
}
