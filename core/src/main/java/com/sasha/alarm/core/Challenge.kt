package com.sasha.alarm.core

/**
 * Чем именно выключается будильник.
 *
 * Отбор жёсткий: годится только то, что **нельзя выполнить лёжа ленивым движением**.
 * По этой причине отброшены тряска телефона, датчик приближения (обманывается
 * ладонью или одеялом), датчик освещённости (владелец спит в маске) и счётчик шагов
 * (решение владельца 2026-08-14: не сработал и не понравился).
 */
enum class Challenge {
    /** Примеры на устный счёт. Лёгкий режим: будит голову, но оставляет в кровати. */
    MATH,

    /** Ловить шарики, пока шкала не дойдёт до нуля. Меряет внимание, а не послушание. */
    REACTION,

    /**
     * Обойти NFC-метки в заданном порядке.
     *
     * Метки регистрируются заранее и получают порядковые номера, из номеров
     * собирается маршрут — хоть `2`, хоть `2 → 1 → 3 → 2`. Пустой маршрут
     * испытанием не является: экран в этом случае идёт по примерам.
     */
    NFC,

    /**
     * Отжимания под камерой.
     *
     * ⚠️ Требует, чтобы телефон стоял поодаль и **человек попадал в кадр целиком**:
     * прогон модели по материалам владельца (2026-08-16) показал, что с телефона,
     * лежащего вплотную, поза либо не находится вовсе, либо дорисовывается наугад.
     */
    PUSHUPS,
    ;

    /** Готово ли испытание к работе. */
    val available: Boolean get() = true
}

/**
 * Испытание на внимание — то, что идёт поверх любого задания.
 *
 * По экрану всё время всплывают кружки, их нужно ловить. Шкала начинается со ста
 * процентов, от каждого пойманного убывает, от каждого упущенного растёт обратно.
 *
 * Смысл в удержании темпа, а не в скорости одного клика: измеряется внимание в
 * течение полуминуты, а его спросонья не изобразить. Промахи дороже попаданий,
 * поэтому вялая игра шкалу не двигает вовсе.
 */
data class ReactionSettings(
    /** Сколько секунд займёт шкала при идеальной игре. */
    val perfectSeconds: Int,
) {
    companion object {
        const val MIN_SECONDS = 10
        const val MAX_SECONDS = 90
        val DEFAULT = ReactionSettings(perfectSeconds = 30)
    }
}

object ReactionMeter {

    /**
     * Как часто рождается новый кружок.
     *
     * Шаг шкалы считается от этого числа, поэтому вдвое более частые кружки дают
     * вдвое меньший шаг — заданное время идеальной игры не меняется.
     */
    const val SPAWN_INTERVAL_MS = 350L

    /** Сколько кружок живёт, прежде чем считается упущенным. */
    const val LIFETIME_MS = 1_600L

    /** Во сколько раз промах дороже попадания. */
    const val MISS_FACTOR = 1.6

    const val START_PERCENT = 100.0

    /** Сколько процентов снимает один пойманный кружок. */
    fun hitStep(settings: ReactionSettings): Double {
        val seconds = settings.perfectSeconds.coerceAtLeast(1)
        val hitsNeeded = seconds * 1000.0 / SPAWN_INTERVAL_MS
        return START_PERCENT / hitsNeeded
    }

    fun onHit(settings: ReactionSettings, progress: Double): Double =
        (progress - hitStep(settings)).coerceIn(0.0, START_PERCENT)

    fun onMiss(settings: ReactionSettings, progress: Double): Double =
        (progress + hitStep(settings) * MISS_FACTOR).coerceIn(0.0, START_PERCENT)

    fun done(progress: Double): Boolean = progress <= 0.0
}
