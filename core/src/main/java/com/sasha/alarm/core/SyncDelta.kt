package com.sasha.alarm.core

/**
 * Что из журнала отдавать компьютеру: всё или только новое.
 *
 * 🔴 **Правило появилось 2026-09-14 по просьбе владельца:** «если телефон передаёт
 * параметры, которые передавались вчера или позавчера, туда, естественно, не нужно».
 * До этого журнал уходил целиком каждый раз — 192 771 строка, около 19 секунд эфира, — и
 * именно эти секунды добили суточную передачу, не уложившуюся в срок приёмника.
 *
 * ⚠️ **Считаем строки в файлах, а не время событий, и это не мелочь.** Журнал лежит
 * помесячными файлами и только дозаписывается; история шагов, догруженная задним числом,
 * дописывается в **старые** файлы, в их конец. Отметка вида «всё, что позже такого-то
 * времени» такую догрузку молча потеряла бы — а счётчик строк в конце файла ловит её верно.
 *
 * 🔴 **Правду о доставленном знает компьютер, а не телефон.** Своя отметка — только
 * ускорение: сколько у него есть, компьютер называет сам ([LogWire.HAVE]), и если стало
 * меньше, чем в прошлый удачный раз, телефон шлёт всё заново. Так сохранено прежнее
 * свойство протокола — хранилище компьютера восстанавливается из телефона, если потеряется.
 *
 * ⚠️ **Сомнение всегда решается в пользу «слать всё».** Лишние строки компьютер отбросит
 * сам, это дёшево; недосланные не заметит никто, и это потерянные данные.
 */
object SyncDelta {

    /** Почему решили так, а не иначе. Нужно журналу: молчаливый выбор не разберёшь потом. */
    enum class Mode {
        /** Компьютер знает, сколько у него есть, и оно на месте — шлём хвосты. */
        INCREMENTAL,

        /** Компьютер промолчал о своём запасе: он старой версии. Шлём всё. */
        FULL_NO_HAVE,

        /** Удачной передачи ещё не было — сверять не с чем. Шлём всё. */
        FULL_FIRST_TIME,

        /** У компьютера стало меньше, чем было: хранилище похудело. Шлём всё. */
        FULL_SHRUNK,
    }

    /**
     * @param skip сколько строк пропустить в начале каждого файла; ключи — все файлы из
     *             `files`, так что забыть файл нельзя даже случайно.
     */
    data class Plan(val mode: Mode, val skip: Map<String, Int>) {
        val full: Boolean get() = mode != Mode.INCREMENTAL
    }

    /**
     * Решить, что отдавать.
     *
     * @param files имя файла журнала → сколько в нём строк сейчас
     * @param delivered имя файла → сколько строк компьютер уже принял (наша отметка)
     * @param haveNow сколько телефонных событий у компьютера сейчас; `null` — не сказал
     * @param haveWhenDelivered сколько их было в момент прошлой удачной передачи
     */
    fun plan(
        files: Map<String, Int>,
        delivered: Map<String, Int>,
        haveNow: Int?,
        haveWhenDelivered: Int?,
    ): Plan {
        val mode = when {
            haveNow == null -> Mode.FULL_NO_HAVE
            haveWhenDelivered == null -> Mode.FULL_FIRST_TIME
            haveNow < haveWhenDelivered -> Mode.FULL_SHRUNK
            else -> Mode.INCREMENTAL
        }
        if (mode != Mode.INCREMENTAL) return Plan(mode, files.mapValues { 0 })

        // ⚠️ Отметка обрезается длиной файла. Файл короче, чем мы «доставили», — значит с
        // ним случилось то, чего мы не понимаем; тогда честнее перечитать его целиком.
        return Plan(mode, files.mapValues { (name, lines) ->
            (delivered[name] ?: 0).coerceIn(0, lines)
        })
    }
}
